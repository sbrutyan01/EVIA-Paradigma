#!/usr/bin/env python3
"""Writes the register declarations the Harmony stub headers need, from a generated program.

The stubs let the checks compile a Harmony application on an ordinary computer, so our own mistakes
show up without Microchip's headers. Re-run this when the runtime starts using another register:

    java -jar target/evia-paradigma-*.jar --gen examples/boards/mqtt_esk2.evia \
         --lang pic32 --board pic32-esk2 --net ethernet -o /tmp/eth.c
    scripts/mqtt/make-harmony-stubs.py /tmp/eth.c > scripts/mqtt/harmony-stubs/registers.h
"""
import re, sys

src = open(sys.argv[1], encoding="utf-8").read()

# what the file defines itself, so we don't declare it twice
defined = set(re.findall(r"^\s*#\s*define\s+([A-Za-z_][A-Za-z0-9_]*)", src, re.M))
defined |= set(re.findall(r"\b(?:static|extern)\s+(?:[A-Za-z_][A-Za-z0-9_ *]*?)([A-Za-z_][A-Za-z0-9_]*)\s*[;(=\[]", src))
defined |= {"INVALID_SOCKET", "IP_ADDRESS_TYPE_IPV4", "TCPIP_DNS_TYPE_A", "TCPIP_DNS_RES_OK",
            "TCPIP_DNS_RES_PENDING", "CPU_CLOCK_FREQUENCY", "PERIPHERAL_CLOCK_FREQUENCY",
            "SYS_Tasks", "TCP_SOCKET", "IP_MULTI_ADDRESS", "TCPIP_NET_HANDLE"}

# the bit fields: SYMBOLbits.MEMBER, including the ones built by token pasting (OC##n##CONbits)
bits = {}
for sym, member in re.findall(r"\b([A-Z][A-Z0-9]*(?:##n##)?[A-Z0-9]*)bits\s*\.\s*([A-Za-z_][A-Za-z0-9_]*)", src):
    for name in ([sym.replace("##n##", str(i)) for i in range(1, 6)] if "##n##" in sym else [sym]):
        bits.setdefault(name, set()).add(member)

# the plain registers: every all-caps word the file uses and does not define
words = set(re.findall(r"\b([A-Z][A-Z0-9]{1,}(?:SET|CLR|INV)?)\b", src))
for sym in list(words):
    if "##n##" in sym:
        words.discard(sym)
for pasted in re.findall(r"\b(?:OC|T)##n##([A-Z0-9]+)\b", src):
    words.update("OC%d%s" % (i, pasted) for i in range(1, 6))
# a register's stem is used both plainly (U1STA = 0) and through its bits (U1STAbits.ON), so declare both
regs = sorted(w for w in words
              if w not in defined and not w.endswith("bits")
              and not re.fullmatch(r"(RT|EVIA|IP|TCPIP|TCP|DNS|UL|HIGH|LOW|INPUT|OUTPUT)[A-Z0-9_]*", w)
              and not re.fullmatch(r"[A-Z]", w))

print("/* Generated by scripts/mqtt/make-harmony-stubs.py: the chip registers the runtime writes to.")
print("   Only for compiling on a computer without Microchip's headers; it declares them, nothing more. */")
print("#ifndef EVIA_HARMONY_STUBS_REGISTERS_H")
print("#define EVIA_HARMONY_STUBS_REGISTERS_H")
print("#include <stdint.h>\n")
for r in regs:
    print(f"extern volatile uint32_t {r};")
print()
for sym in sorted(bits):
    members = " ".join(f"unsigned int {m} : 4;" for m in sorted(bits[sym]))
    print(f"extern volatile struct {{ {members} }} {sym}bits;")
print("\n#endif")
